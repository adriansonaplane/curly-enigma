'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const context = { globalThis: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/factions.js', 'utf8'), context);
const F = context.globalThis.Factions;
const migrated = F.migrate({ haven: 9000, light: -9999, unknown: 50 });
assert.strictEqual(F.value(migrated, 'haven'), F.MAX);
assert.strictEqual(F.value(migrated, 'light'), F.MIN);
assert.strictEqual(migrated.values.unknown, undefined);
const state = F.create();
F.change(state, 'haven', 1200);
assert.strictEqual(F.tier(F.value(state, 'haven')).name, 'Friendly');
assert.strictEqual(F.value(state, 'cinder'), -300, 'rival standing changes in the opposite direction');
assert.strictEqual(F.price(100, state, 'haven'), 95);
F.change(state, 'ironsong', -4000, { rivals: false });
assert.strictEqual(F.isHostile(state, 'ironsong'), true);
assert.strictEqual(F.hasAccess(state, 'ironsong'), false);
console.log('faction reputation migration and rules passed');
